/* ── Helpers ─────────────────────────────────────────────── */

const series = (text: string) => text.split(" ").map(Number);
const add = <T extends number[]>(a: T, b: readonly number[]) => a.map((v, i) => v + (b[i] ?? 0)) as T;
const zeros = <T extends number[]>(n: number) => Array.from({ length: n }, () => 0) as T;
const scoped = (scope: Scope) => COUNTRIES.filter(c => inScope(scope, c.region, c.code)).map(c => c.code);
const FORMAT_LABEL: Record<StoreFormat, string> = { flagship: "Flagship", standard: "Standard", express: "Express" };

/** Seeds of one key, added up over the countries asked for. */
type Acc = { country: CountryCode; countries: CountryCode[]; label: string; sums: Record<BusinessPeriod, Sums>; revenue: number[]; lost: number[] };
function collect(dim: Seed[1], countries: CountryCode[]): Map<string, Acc> {
  const out = new Map<string, Acc>();
  for (const seed of SEEDS) {
    if (seed[1] !== dim || !countries.includes(seed[0])) continue;
    const [cc, , key, today, week, season, rev, lost] = seed;
    const acc = out.get(key) ?? { country: cc, countries: [], label: CITY_NAME[key] ?? key, sums: { today: zeros<Sums>(10), "7d": zeros<Sums>(10), season: zeros<Sums>(10) }, revenue: zeros(28), lost: zeros(28) };
    acc.countries.push(cc);
    acc.sums = { today: add(acc.sums.today, today), "7d": add(acc.sums["7d"], week), season: add(acc.sums.season, season) };
    acc.revenue = add(acc.revenue, series(rev));
    acc.lost = add(acc.lost, series(lost));
    out.set(key, acc);
  }
  return out;
}

function measure(s: Sums, metric: BreakdownMetric): BreakdownValue {
  if (metric === "revenue") return { value: s[0], plan: s[1], ly: s[2] };
  if (metric === "margin") return { value: s[3], plan: s[4], ly: s[5] };
  if (metric === "units") return { value: s[6], plan: s[7], ly: s[8] };
  return { value: s[9], plan: null, ly: null };
}

/** Oct 28 (the last date) is still running for every country but Japan, which is on Oct 29 and not open yet. */
const partialFor = (countries: CountryCode[]) => countries.some(cc => cc !== "JP") ? { partialFrom: 27 } : {};

/** A breakdown row for one period. Margin and units by day follow revenue at the row's 7-day margin and price. */
function rowOf(acc: Acc, period: BusinessPeriod, extra: Partial<BreakdownRow>): Omit<BreakdownRow, "key" | "label"> {
  const s = acc.sums[period], week = acc.sums["7d"];
  const gmRate = week[0] ? week[3] / week[0] : 0, perDollar = week[0] ? week[6] / week[0] : 0;
  return {
    ...extra,
    ...partialFor(acc.countries),
    values: { revenue: measure(s, "revenue"), margin: measure(s, "margin"), units: measure(s, "units"), lost: measure(s, "lost") },
    lostShare: s[0] + s[9] ? s[9] / (s[0] + s[9]) : null,
    trend: { revenue: acc.revenue, margin: acc.revenue.map(v => Math.round(v * gmRate)), units: acc.revenue.map(v => Math.round(v * perDollar)), lost: acc.lost },
  };
}

/* ── Breakdown ───────────────────────────────────────────── */

/** The Breakdown table: country rows hold the scope's whole region, every other dimension is narrowed to the scope. */
export function breakdownFor(scope: Scope): Record<BreakdownDim, Record<BusinessPeriod, BreakdownRow[]>> {
  const inside = scoped(scope);
  const region = scoped({ ...scope, country: null });
  const per = (make: (period: BusinessPeriod) => BreakdownRow[]) => Object.fromEntries(PERIODS.map(p => [p, make(p)])) as Record<BusinessPeriod, BreakdownRow[]>;

  const countries = collect("country", region), cities = collect("city", inside), formats = collect("format", inside), varieties = collect("variety", inside);
  const ch = inside.reduce((acc, cc) => ({
    inStore: add(acc.inStore, series(CHANNELS[cc].inStore)), online: add(acc.online, series(CHANNELS[cc].online)),
    sums: Object.fromEntries(PERIODS.map(p => [p, add(acc.sums[p], CHANNELS[cc][p])])) as Record<BusinessPeriod, [number, number]>,
  }), { inStore: zeros<number[]>(28), online: zeros<number[]>(28), sums: { today: [0, 0], "7d": [0, 0], season: [0, 0] } as Record<BusinessPeriod, [number, number]> });

  return {
    country: per(p => [...countries].map(([key, acc]) => {
      const meta = COUNTRIES.find(c => c.code === key)!;
      return { key, label: meta.name, ...rowOf(acc, p, { country: { code: meta.code, region: meta.region } }) };
    })),
    city: per(p => [...cities].map(([key, acc]) => ({ key, label: acc.label, ...rowOf(acc, p, { sublabel: countryName(acc.country), countryCode: acc.country, cityKey: key }) }))),
    format: per(p => [...formats].map(([key, acc]) => ({ key, label: FORMAT_LABEL[key as StoreFormat], ...rowOf(acc, p, { format: key as StoreFormat }) }))),
    variety: per(p => [...varieties].map(([key, acc]) => ({ key, label: key, ...rowOf(acc, p, {}) }))),
    channel: per(p => inside.length ? [
      { key: "in_store", label: "In store", values: { revenue: { value: ch.sums[p][0], plan: null, ly: null } }, lostShare: null, trend: { revenue: ch.inStore }, ...partialFor(inside) },
      { key: "online", label: "Online", values: { revenue: { value: ch.sums[p][1], plan: null, ly: null } }, lostShare: null, trend: { revenue: ch.online }, ...partialFor(inside) },
    ] : []),
  };
}

/* ── Mix ─────────────────────────────────────────────────── */

/**
 * Mix per period: varieties (with last season's revenue for the shift, and units sold for the Average selling
 * price tile) and channels. Channel units are null, as they are live.
 */
export function mixFor(scope: Scope): Record<BusinessPeriod, BusinessMix> {
  const inside = scoped(scope);
  const varieties = collect("variety", inside);
  return Object.fromEntries(PERIODS.map(p => {
    const [inStore, online] = inside.reduce<[number, number]>((acc, cc) => add(acc, CHANNELS[cc][p]), [0, 0]);
    return [p, {
      varieties: VARIETIES.map((variety: Variety) => {
        const s = varieties.get(variety)?.sums[p];
        return { variety, revenue: s?.[0] ?? 0, grossMargin: s?.[3] ?? 0, lyRevenue: s?.[2] ?? 0, units: s?.[6] ?? 0 };
      }),
      channels: [{ channel: "in_store", revenue: inStore, units: null }, { channel: "online", revenue: online, units: null }],
    } satisfies BusinessMix];
  })) as Record<BusinessPeriod, BusinessMix>;
}

