/** Wed 28 Oct, the local today of every country but Japan, and the chart's last date. */
const TODAY = Date.UTC(2026, 9, 28);

/** The chart's 28 local dates (Oct 1 to Oct 28), oldest first, summed over the scope. Oct 28 is partial unless the scope is only Japan. */
export function daysFor(scope: Scope): BusinessDay[] {
  const inside = scoped(scope);
  return Array.from({ length: 28 }, (_, i) => {
    const [revenue, planRevenue, lyRevenue, grossMargin, unitsSold, deliveryCost, shrink, lostRevenue] =
      inside.reduce((acc, cc) => add(acc, DAYS[cc][i]), zeros<number[]>(8));
    const date = new Date(TODAY + (i - 27) * 864e5);
    const dow = date.getUTCDay();
    return {
      date: date.toISOString().slice(0, 10), revenue, planRevenue, lyRevenue, grossMargin, unitsSold, deliveryCost, shrink, lostRevenue,
      isWeekend: dow === 0 || dow === 6, isPartial: i === 27 && inside.some(cc => cc !== "JP"),
    };
  });
}

/** The scope's local today (vm.today): Thu 29 Oct for Japan alone (its day has not begun), else Wed 28 Oct. */
export const todayFor = (scope: Scope): string => {
  const inside = scoped(scope);
  return inside.length && inside.every(cc => cc === "JP") ? "2026-10-29" : "2026-10-28";
};

/** Events of the scope's countries, oldest first. */
export const eventsFor = (scope: Scope): BusinessEvent[] => {
  const inside = scoped(scope);
  return EVENTS.filter(e => inside.includes(e.countryCode));
};

/** Lost sales by cause per period, for the Lost sales panel's totals. */
export function lostByCauseFor(scope: Scope): Record<BusinessPeriod, Record<LostCause, number>> {
  const inside = scoped(scope);
  return Object.fromEntries(PERIODS.map(p => {
    const [late, short, demand] = inside.reduce<[number, number, number]>((acc, cc) => add(acc, LOST[cc][p]), [0, 0, 0]);
    return [p, { late_delivery: late, hub_shortage: short, demand_above_plan: demand }];
  })) as Record<BusinessPeriod, Record<LostCause, number>>;
}

